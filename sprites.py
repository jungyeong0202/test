"""도트(픽셀) 스프라이트 데이터.

외부 이미지 파일이나 네트워크 없이, 문자 그리드로 포켓몬 도트를 정의한다.
각 문자는 팔레트의 색(#RRGGBB)에 대응하고 '.' 은 투명 픽셀이다.

이 모듈은 tkinter에 의존하지 않으므로 GUI 없이도 검증/테스트가 가능하다.
"""

from __future__ import annotations


class Pokemon:
    """한 마리의 도트 그림과 걷기 애니메이션 정보.

    두 가지 방식으로 정의할 수 있다.

    * rows + step_rows : 손으로 그린 스프라이트. 기본 자세와, 두 번째 프레임에서
      바꿔 끼울 줄만 적는다.
    * frame_rows       : 프레임마다 전체 줄을 적는다. tools/import_sprite.py 가
      이미지에서 만들어 내는 형식이다.
    """

    def __init__(self, key, name_ko, palette, rows=None, step_rows=None,
                 frame_rows=None, scale_factor=1.0, bounce=True, facing="right",
                 move="walk", pose_rows=None):
        self.key = key
        self.name_ko = name_ko
        self.palette = palette
        # --scale 에 곱해질 배율. 도트가 촘촘한 그림일수록 작게 잡는다.
        self.scale_factor = scale_factor
        # 프로그램이 홀수 프레임마다 살짝 띄워 주는 흔들림을 쓸지 여부.
        # 프레임 안에 이미 몸통 움직임이 그려져 있으면 끈다.
        self.bounce = bounce
        # 원본 그림이 어느 쪽을 보고 있는지. 이동 방향과 다르면 좌우로 뒤집는다.
        if facing not in ("left", "right"):
            raise ValueError("%s: facing 은 'left' 또는 'right' 여야 합니다" % key)
        self.facing = facing
        # 걷기 프레임 말고 상황에 따라 쓰는 자세들.
        # 같은 도트를 눌러 놓거나 늘여서 만든 것이라 새 그림이 필요 없다.
        #   squash  눌린 자세 (착지 반동)
        #   stretch 늘어난 자세 (공중)
        #   blink   눈을 감은 자세
        self.pose_rows = {name: list(rows) for name, rows in (pose_rows or {}).items()}

        # 걸어 다닐지(walk), 폴짝 뛰어 다닐지(hop).
        # hop 은 프레임이 [평소, 웅크림, 늘어남] 순서라고 본다.
        if move not in ("walk", "hop"):
            raise ValueError("%s: move 는 'walk' 또는 'hop' 이어야 합니다" % key)
        self.move = move

        if frame_rows:
            self.frame_rows = [list(frame) for frame in frame_rows]
            self.rows = self.frame_rows[0]
            self.step_rows = {}
        else:
            if not rows:
                raise ValueError("%s: rows 또는 frame_rows 가 필요합니다" % key)
            self.rows = list(rows)
            self.step_rows = step_rows or {}
            stepped = list(self.rows)
            for index, replacement in self.step_rows.items():
                stepped[index] = replacement
            self.frame_rows = [self.rows, stepped]

    # --- 그리드 만들기 -------------------------------------------------
    def width(self):
        blocks = list(self.frame_rows) + list(self.pose_rows.values())
        return max(len(row) for block in blocks for row in block)

    def _grid(self, rows, width):
        grid = []
        for row in rows:
            row = row.ljust(width, ".")
            grid.append([None if ch == "." else self.palette[ch] for ch in row])
        return grid

    def frames(self):
        """걷기 프레임(색상 그리드) 목록을 돌려준다."""
        width = self.width()
        return [self._grid(frame, width) for frame in self.frame_rows]

    def poses(self):
        """이름별 자세(색상 그리드). 없으면 빈 딕셔너리."""
        width = self.width()
        return {name: self._grid(rows, width) for name, rows in self.pose_rows.items()}

    # --- 검증 -----------------------------------------------------------
    def validate(self):
        heights = {len(frame) for frame in self.frame_rows}
        if len(heights) != 1:
            raise ValueError("%s: 프레임마다 줄 수가 다릅니다" % self.key)
        for name, rows in self.pose_rows.items():
            if len(rows) != len(self.frame_rows[0]):
                raise ValueError("%s: 자세 %s 의 줄 수가 프레임과 다릅니다" % (self.key, name))
        for number, frame in enumerate(list(self.frame_rows) + list(self.pose_rows.values())):
            for index, row in enumerate(frame):
                for ch in row:
                    if ch != "." and ch not in self.palette:
                        raise ValueError(
                            "%s: %d번 프레임 %d행에 팔레트에 없는 문자 %r 이 있습니다"
                            % (self.key, number, index, ch)
                        )
        if self.scale_factor <= 0:
            raise ValueError("%s: scale_factor 는 0보다 커야 합니다" % self.key)


